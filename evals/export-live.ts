import { createRepositoryReviewCases } from "./repository-cases";
import { createGuideInteractionCases, createGuideReviewCases, createGuideRegressionCases } from "./guide-cases";
import { createFrozenCases } from './frozen-cases';
import { mkdirSync, writeFileSync } from "node:fs";
import { createLearningLiveCases } from "./learning-live-cases";
import { createLiveCases } from "./live-cases";
import { createEnglishCases, createSessionCases } from "./session-cases";
mkdirSync(".superpowers/model-run", { recursive: true });
const repository = process.argv.includes("--repository");
const guideRegression = process.argv.includes("--guide-regression");
const guides = process.argv.includes("--guides");
const guideReview = process.argv.includes("--guide-review");
const learning = process.argv.includes("--learning");
const english = process.argv.includes("--english");
const frozen = process.argv.includes("--frozen");
const sessions = process.argv.includes("--sessions");
if ([learning, english, sessions, frozen, guides, guideReview, guideRegression, repository].filter(Boolean).length > 1) throw new Error('Choose one suite');
const cases = repository ? createRepositoryReviewCases() : guideRegression ? createGuideRegressionCases() : guides ? createGuideInteractionCases() : guideReview ? createGuideReviewCases() : frozen ? createFrozenCases() : sessions ? createSessionCases() : english ? createEnglishCases() : learning ? createLearningLiveCases() : createLiveCases();
const filename = repository ? 'repository-review-cases' : guideRegression ? 'guide-regression-cases' : guides ? 'guide-session-cases' : guideReview ? 'guide-review-cases' : frozen ? 'frozen-cases' : sessions ? 'session-cases' : english ? 'english-cases' : learning ? 'learning-cases' : 'cases';
writeFileSync(`.superpowers/model-run/${filename}.json`, JSON.stringify(cases, null, 2) + "\n");
console.log(`Exported ${cases.length} ${sessions || frozen || guides || guideRegression ? 'actual-history session' : 'isolated'} live evaluation cases.`);
