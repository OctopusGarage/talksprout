import { createFrozenCases } from './frozen-cases';
import { mkdirSync, writeFileSync } from "node:fs";
import { createLearningLiveCases } from "./learning-live-cases";
import { createLiveCases } from "./live-cases";
import { createEnglishCases, createSessionCases } from "./session-cases";
mkdirSync(".superpowers/model-run", { recursive: true });
const learning = process.argv.includes("--learning");
const english = process.argv.includes("--english");
const frozen = process.argv.includes("--frozen");
const sessions = process.argv.includes("--sessions");
if ([learning, english, sessions, frozen].filter(Boolean).length > 1) throw new Error('Choose one suite');
const cases = frozen ? createFrozenCases() : sessions ? createSessionCases() : english ? createEnglishCases() : learning ? createLearningLiveCases() : createLiveCases();
const filename = frozen ? 'frozen-cases' : sessions ? 'session-cases' : english ? 'english-cases' : learning ? 'learning-cases' : 'cases';
writeFileSync(`.superpowers/model-run/${filename}.json`, JSON.stringify(cases, null, 2) + "\n");
console.log(`Exported ${cases.length} ${sessions || frozen ? 'actual-history session' : 'isolated'} live evaluation cases.`);
